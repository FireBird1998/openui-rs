// swift-tools-version: 6.0
// The viewer: plays OpenUI Lang programs as streams and draws them natively.
// Build it with scripts/viewer.sh, which first builds the core's binding into
// Frameworks/ and its Swift bindings into Sources/OpenUIFFI/ (both generated,
// not committed).
import PackageDescription

let package = Package(
    name: "Viewer",
    platforms: [.macOS("27.0")],
    products: [
        .executable(name: "Viewer", targets: ["Viewer"]),
    ],
    targets: [
        // The core's UniFFI binding: a static library plus its C header.
        .binaryTarget(name: "openui_ffiFFI", path: "Frameworks/openui_ffiFFI.xcframework"),
        // The Swift side of the binding, generated by uniffi-bindgen.
        .target(
            name: "OpenUIFFI",
            dependencies: ["openui_ffiFFI"],
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        // Everything but the app's entry point, so tests can reach it.
        .target(name: "ViewerKit", dependencies: ["OpenUIFFI"]),
        .executableTarget(name: "Viewer", dependencies: ["ViewerKit"]),
        .testTarget(name: "ViewerKitTests", dependencies: ["ViewerKit"]),
    ]
)
