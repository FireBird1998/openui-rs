// swift-tools-version: 6.0
// OpenUINative: the core's Swift binding, and OpenUI Lang programs drawn as
// native SwiftUI views. scripts/swift-binding.sh builds the binding into
// Frameworks/ and its Swift side into Sources/OpenUIFFI/ (both generated,
// not committed); build those first.
import PackageDescription

let package = Package(
    name: "OpenUINative",
    platforms: [.macOS("27.0")],
    products: [
        .library(name: "OpenUINative", targets: ["OpenUINative"]),
    ],
    targets: [
        // The core's UniFFI binding: a static library plus its C header.
        .binaryTarget(name: "openui_ffiFFI", path: "Frameworks/openui_ffiFFI.xcframework"),
        // The Swift side of the binding, generated by uniffi-bindgen.
        .target(
            name: "OpenUIFFI",
            dependencies: ["openui_ffiFFI"],
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        .target(name: "OpenUINative", dependencies: ["OpenUIFFI"]),
        .testTarget(name: "OpenUINativeTests", dependencies: ["OpenUINative", "OpenUIFFI"]),
    ]
)
