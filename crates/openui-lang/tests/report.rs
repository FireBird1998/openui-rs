//! The counts in `CONFORMANCE.md` are what the corpus and goldens hold. The
//! block between the `counts` markers is generated here; if it's stale this
//! test fails with the fresh block, and `UPDATE_REPORT=1` rewrites it.

mod common;

use std::collections::BTreeMap;
use std::fmt::Write as _;

use common::{PENDING_LISTS, Pending, conformance_dir, golden_dir, read, repo_root};
use openui_lang::parse_json;
use serde_json::Value;

const START: &str = "<!-- counts: generated by tests/report.rs; UPDATE_REPORT=1 cargo test --test report rewrites it -->";
const END: &str = "<!-- /counts -->";

fn manifest(file: &str) -> Value {
    let path = conformance_dir().join(file);
    if path.exists() {
        parse_json(&read(&path)).unwrap()
    } else {
        serde_json::json!({"cases": []})
    }
}

fn cases(files: &[&str]) -> Vec<Value> {
    files
        .iter()
        .flat_map(|f| manifest(f)["cases"].as_array().unwrap().clone())
        .collect()
}

/// `1234567` as `1,234,567`.
fn n(count: usize) -> String {
    let digits = count.to_string();
    let mut out = String::new();
    for (i, c) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i).is_multiple_of(3) {
            out.push(',');
        }
        out.push(c);
    }
    out
}

fn by_source(cases: &[Value]) -> BTreeMap<String, usize> {
    let mut counts = BTreeMap::new();
    for c in cases {
        *counts
            .entry(c["source"].as_str().unwrap_or("?").to_owned())
            .or_default() += 1;
    }
    counts
}

fn sources(counts: &BTreeMap<String, usize>) -> String {
    counts
        .iter()
        .map(|(source, count)| format!("{} {source}", n(*count)))
        .collect::<Vec<_>>()
        .join(", ")
}

fn block() -> String {
    let upstream = read(&repo_root().join("reference/UPSTREAM"));
    let field = |name: &str| {
        upstream
            .lines()
            .find_map(|l| l.strip_prefix(&format!("{name}: ")))
            .unwrap()
            .to_owned()
    };

    // The parse corpus, its streaming steps and its stage prefixes.
    let corpus = cases(&[
        "manifest.json",
        "imported.json",
        "fuzz.json",
        "synthetic.json",
        "recorded.json",
    ]);
    let (mut steps, mut prefixes, mut staged, mut roots) = (0, 0, 0, 0);
    for c in &corpus {
        let name = c["name"].as_str().unwrap();
        let golden = parse_json(&read(&golden_dir().join(format!("{name}.steps.json")))).unwrap();
        steps += 1 + golden
            .as_object()
            .unwrap()
            .values()
            .map(|chunking| chunking["steps"].as_array().unwrap().len())
            .sum::<usize>();
        if c.get("stages") != Some(&Value::Bool(false)) {
            staged += 1;
            prefixes += read(&conformance_dir().join(c["file"].as_str().unwrap()))
                .chars()
                .count();
        }
        let oneshot =
            parse_json(&read(&golden_dir().join(format!("{name}.oneshot.json")))).unwrap();
        roots += usize::from(!oneshot["root"].is_null());
    }
    let prompts = std::fs::read_dir(conformance_dir().join("prompts"))
        .unwrap()
        .filter(|e| {
            e.as_ref()
                .unwrap()
                .path()
                .extension()
                .is_some_and(|x| x == "json")
        })
        .count();
    let merges = cases(&[
        "imported/merge.json",
        "merge.json",
        "merge-generated.json",
        "merge-fuzz.json",
        "merge-recorded.json",
    ]);
    let serializes = cases(&[
        "imported/serialize.json",
        "serialize.json",
        "serialize-fuzz.json",
    ]);
    let serialize_sources = {
        let mut counts = by_source(&serializes);
        counts.insert("parse corpus root".to_owned(), roots);
        counts
    };
    let enrich = parse_json(&read(&golden_dir().join("edits/enrich.json"))).unwrap();
    let quirks = read(&conformance_dir().join("QUIRKS.md"))
        .lines()
        .filter(|l| l.starts_with("## "))
        .count();

    let mut out = String::new();
    let _ = writeln!(out, "{START}");
    let _ = writeln!(
        out,
        "Reference: `{}` at commit `{}` (`{}`), vendored {}.\n",
        field("package"),
        field("commit"),
        field("path"),
        field("vendored")
    );
    let _ = writeln!(
        out,
        "| Compared with the reference | Cases | Checks | Cases by source |"
    );
    let _ = writeln!(out, "|---|---:|---:|---|");
    let _ = writeln!(
        out,
        "| Parse results: one-shot, and after every push and at the end of 8 chunkings, 2 resync sequences and any recorded chunks | {} | {} results | {} |",
        n(corpus.len()),
        n(steps),
        sources(&by_source(&corpus))
    );
    let _ = writeln!(
        out,
        "| Stages on every prefix: preprocessing, tokens, statements and expression trees | {} | {} prefixes | the parse corpus, less its largest synthetic programs |",
        n(staged),
        n(prefixes)
    );
    let _ = writeln!(
        out,
        "| System prompts | {} | {} | |",
        n(prompts),
        n(prompts)
    );
    let _ = writeln!(
        out,
        "| Edit-mode merges | {} | {} | {} |",
        n(merges.len()),
        n(merges.len()),
        sources(&by_source(&merges))
    );
    let serialize_total: usize = serialize_sources.values().sum();
    let _ = writeln!(
        out,
        "| Element trees back to source | {} | {} | {} |",
        n(serialize_total),
        n(serialize_total),
        sources(&serialize_sources)
    );
    let _ = writeln!(
        out,
        "| Enriched errors | {} | {} | every parse corpus case with errors |",
        n(enrich.as_object().unwrap().len()),
        n(enrich.as_object().unwrap().len())
    );
    let _ = writeln!(out, "\nQuirks recorded: {quirks}.");
    let pending: Vec<String> = PENDING_LISTS
        .iter()
        .map(|(list, what)| (Pending::load(list).len(), what))
        .filter(|(count, _)| *count > 0)
        .map(|(count, what)| format!("{} {what}", n(count)))
        .collect();
    let _ = writeln!(
        out,
        "Not matched yet, listed in `conformance/pending/`: {}.",
        if pending.is_empty() {
            "none".to_owned()
        } else {
            pending.join(", ")
        }
    );
    let _ = write!(out, "{END}");
    out
}

#[test]
fn the_report_counts_what_the_corpus_holds() {
    let path = repo_root().join("CONFORMANCE.md");
    let report = read(&path);
    let fresh = block();
    let (Some(start), Some(end)) = (report.find(START), report.find(END)) else {
        panic!("CONFORMANCE.md has no counts block; add one between:\n{START}\n{END}");
    };
    let current = &report[start..end + END.len()];
    if current == fresh {
        return;
    }
    if std::env::var_os("UPDATE_REPORT").is_some() {
        let updated = format!("{}{fresh}{}", &report[..start], &report[end + END.len()..]);
        std::fs::write(&path, updated).unwrap();
        return;
    }
    panic!(
        "CONFORMANCE.md's counts are stale. Fresh block (or run with UPDATE_REPORT=1):\n\n{fresh}"
    );
}
